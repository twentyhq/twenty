import { describe, expect, it } from 'vitest';

import { mapTeamsTranscriptToEntries } from 'src/features/transcripts/logic-functions/utils/map-teams-transcript-to-entries';

describe('mapTeamsTranscriptToEntries', () => {
  it('should merge consecutive cues from the same speaker into one entry', () => {
    const content = [
      'WEBVTT',
      '',
      '0f6b1c1e-6c8a-4f5e-9b3a-2d7f0e1a9c4b/17-0',
      '00:00:06.360 --> 00:00:09.840',
      "<v Alice Martin>So today we're going to go through the</v>",
      '',
      '0f6b1c1e-6c8a-4f5e-9b3a-2d7f0e1a9c4b/17-1',
      '00:00:09.840 --> 00:00:12.200',
      '<v Alice Martin>plan for the next quarter.</v>',
      '',
      '0f6b1c1e-6c8a-4f5e-9b3a-2d7f0e1a9c4b/21-0',
      '00:01:02.500 --> 00:01:04.000',
      '<v Bob Chen>Sounds good.</v>',
      '',
      '0f6b1c1e-6c8a-4f5e-9b3a-2d7f0e1a9c4b/24-0',
      '01:00:03.000 --> 01:00:05.000',
      '<v Alice Martin>Thanks, everyone.</v>',
      '',
    ].join('\n');

    expect(mapTeamsTranscriptToEntries(content)).toEqual([
      {
        participant: { name: 'Alice Martin' },
        words: [
          {
            text: "So today we're going to go through the",
            start_timestamp: { relative: 6.36 },
          },
          {
            text: 'plan for the next quarter.',
            start_timestamp: { relative: 9.84 },
          },
        ],
      },
      {
        participant: { name: 'Bob Chen' },
        words: [{ text: 'Sounds good.', start_timestamp: { relative: 62.5 } }],
      },
      {
        participant: { name: 'Alice Martin' },
        words: [
          { text: 'Thanks, everyone.', start_timestamp: { relative: 3603 } },
        ],
      },
    ]);
  });

  it('should keep one entry per cue when the transcript has no speaker attribution', () => {
    const content = [
      '00:00:01.500 --> 00:00:04.000 ',
      '',
      'Hello, thanks for joining. ',
      '',
      '00:00:04.000 --> 00:00:07.200 ',
      '',
      'Glad to be here. ',
      '',
    ].join('\r\n');

    expect(mapTeamsTranscriptToEntries(content)).toEqual([
      {
        participant: { name: null },
        words: [
          {
            text: 'Hello, thanks for joining.',
            start_timestamp: { relative: 1.5 },
          },
        ],
      },
      {
        participant: { name: null },
        words: [{ text: 'Glad to be here.', start_timestamp: { relative: 4 } }],
      },
    ]);
  });

  it('should start speech captured before the transcription began at zero', () => {
    const content = [
      'WEBVTT',
      '',
      '-00:00:02.000 --> 00:00:01.000',
      '<v Alice Martin>We can start.</v>',
    ].join('\n');

    expect(mapTeamsTranscriptToEntries(content)).toEqual([
      {
        participant: { name: 'Alice Martin' },
        words: [{ text: 'We can start.', start_timestamp: { relative: 0 } }],
      },
    ]);
  });

  it('should decode entities and skip notes and cues without words', () => {
    const content = [
      '﻿WEBVTT',
      '',
      'NOTE Generated by Microsoft Teams',
      '',
      '00:00:01.000 --> 00:00:02.000',
      '<v Alice Martin>R&amp;D &lt;3 the &quot;new&quot; plan</v>',
      '',
      '00:00:02.000 --> 00:00:03.000',
      '<v Bob Chen></v>',
    ].join('\n');

    expect(mapTeamsTranscriptToEntries(content)).toEqual([
      {
        participant: { name: 'Alice Martin' },
        words: [
          {
            text: 'R&D <3 the "new" plan',
            start_timestamp: { relative: 1 },
          },
        ],
      },
    ]);
  });

  it('should return no entries when Microsoft has no cues yet', () => {
    expect(mapTeamsTranscriptToEntries('WEBVTT\n\n')).toEqual([]);
  });
});
