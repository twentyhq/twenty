const SPECIAL_CHARACTERS_REGEX =
  /[ÆÐØÞßæðøþĐđĦħıİĲĳĸĿŀŁłŉŊŋŒœŦŧſƀƁƂƃƇƈƉƊƋƌƐƑƒƓƕƖƗƘƙƚƝƞƢƣƤƥƫƬƭƮƲƳƴƵƶǄǅǆǇǈǉǊǋǌǤǥǱǲǳȡȤȥȴȵȶȷȸȹȺȻȼȽȾȿɀɃɄɆɇɈɉɌɍɎɏẚẛẞ]/g;

export const stripAccents = (str: string): string => {
  if (typeof str !== 'string') {
    return str;
  }

  return str
    .replace(
      SPECIAL_CHARACTERS_REGEX,
      (match) => SPECIAL_CHARACTERS_MAP[match] ?? match,
    )
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
};
