import { PageLayoutType } from '@/types/page-layout/PageLayoutType';
import { WidgetType } from '@/types/page-layout/WidgetType';

const RECORD_CONTENT_PAGE_LAYOUT_TYPES = [
  PageLayoutType.RECORD_PAGE,
  PageLayoutType.RECORD_INDEX,
  PageLayoutType.DASHBOARD,
  PageLayoutType.STANDALONE_PAGE,
] as const;

export const SUPPORTED_PAGE_LAYOUT_TYPES_BY_WIDGET_TYPE: Record<
  WidgetType,
  readonly PageLayoutType[]
> = {
  [WidgetType.VIEW]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.IFRAME]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.FIELD]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.FIELDS]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.GRAPH]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.STANDALONE_RICH_TEXT]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.TIMELINE]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.TASKS]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.NOTES]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.FILES]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.EMAILS]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.CALENDAR]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.FIELD_RICH_TEXT]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.WORKFLOW]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.WORKFLOW_VERSION]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.WORKFLOW_RUN]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.FRONT_COMPONENT]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.RECORD_TABLE]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.EMAIL_THREAD]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.CALL_RECORDING_SUMMARY]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.CALL_RECORDING_TRANSCRIPT]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.MESSAGE_CAMPAIGN_BODY]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.MESSAGE_CAMPAIGN_DETAILS]: RECORD_CONTENT_PAGE_LAYOUT_TYPES,
  [WidgetType.FORM_FIELD]: [PageLayoutType.RECORD_FORM],
};

export const isWidgetTypeSupportedInPageLayoutType = ({
  widgetType,
  pageLayoutType,
}: {
  widgetType: WidgetType;
  pageLayoutType: PageLayoutType;
}): boolean =>
  SUPPORTED_PAGE_LAYOUT_TYPES_BY_WIDGET_TYPE[widgetType].includes(
    pageLayoutType,
  );
