import { ApiService } from '@/cli/utilities/api/api-service';
import { resolveClientSdkPackageRoot } from '@/cli/utilities/client/resolve-client-sdk-package-root';
import {
  generateCoreClientSource,
  replaceCoreClient,
} from 'twenty-client-sdk/generate';
import { isDefined } from 'twenty-shared/utils';

export class ClientService {
  private apiService: ApiService;

  constructor(options?: {
    serverUrl?: string;
    token?: string;
    skipAuth?: boolean;
  }) {
    this.apiService = new ApiService({
      disableInterceptors: true,
      serverUrl: options?.serverUrl,
      skipAuth: options?.skipAuth ?? true,
      token: options?.token,
    });
  }

  async generateCoreClient({
    appPath,
    appAccessToken,
  }: {
    appPath: string;
    appAccessToken?: string;
  }): Promise<void> {
    const packageRoot = await resolveClientSdkPackageRoot(appPath);

    if (!isDefined(packageRoot)) {
      throw new Error(
        `Cannot find twenty-client-sdk in ${appPath} or any parent directory. Install it first: yarn add twenty-client-sdk`,
      );
    }

    const schema = await this.introspectCoreSchema({ appAccessToken });

    await replaceCoreClient({ packageRoot, schema });
  }

  async generateCoreClientToPath({
    outputPath,
    typesOnly,
    remoteUrl,
    appAccessToken,
  }: {
    outputPath: string;
    typesOnly: boolean;
    remoteUrl: string;
    appAccessToken?: string;
  }): Promise<void> {
    const schema = await this.introspectCoreSchema({ appAccessToken });

    await generateCoreClientSource({
      schema,
      outputPath,
      typesOnly,
      provenanceHeader: `@generated by twenty dev:generate-client from ${remoteUrl}`,
    });
  }

  private async introspectCoreSchema({
    appAccessToken,
  }: {
    appAccessToken?: string;
  }): Promise<string> {
    const coreSchemaResponse = await this.apiService.getSchema({
      appAccessToken,
    });

    if (!coreSchemaResponse.success) {
      throw new Error(
        `Failed to introspect core schema: ${JSON.stringify(coreSchemaResponse.error)}`,
      );
    }

    return coreSchemaResponse.data;
  }
}
