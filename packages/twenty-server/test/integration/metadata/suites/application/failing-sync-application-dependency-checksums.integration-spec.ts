import { buildBaseManifest } from 'test/integration/metadata/suites/application/utils/build-base-manifest.util';
import { cleanupApplicationAndAppRegistration } from 'test/integration/metadata/suites/application/utils/cleanup-application-and-app-registration.util';
import { setupApplicationForSync } from 'test/integration/metadata/suites/application/utils/setup-application-for-sync.util';
import { syncApplication } from 'test/integration/metadata/suites/application/utils/sync-application.util';
import { uploadApplicationFile } from 'test/integration/metadata/suites/application/utils/upload-application-file.util';
import {
  computeDependencyFileChecksum,
  computePackageJsonChecksum,
  type Manifest,
} from 'twenty-shared/application';
import { v4 as uuidv4 } from 'uuid';

const TEST_APP_ID = uuidv4();
const TEST_ROLE_ID = uuidv4();

const TEST_YARN_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1
`;

const buildManifestDeclaring = (
  declaredChecksums: Pick<
    Manifest['application'],
    'packageJsonChecksum' | 'yarnLockChecksum'
  >,
): Manifest => {
  const baseManifest = buildBaseManifest({
    appId: TEST_APP_ID,
    roleId: TEST_ROLE_ID,
  });

  return {
    ...baseManifest,
    application: { ...baseManifest.application, ...declaredChecksums },
  };
};

describe('Failing sync application - dependency checksums', () => {
  beforeEach(async () => {
    await setupApplicationForSync({
      applicationUniversalIdentifier: TEST_APP_ID,
      name: 'Test Application',
      description: 'App for testing dependency checksum verification',
      sourcePath: 'test-sync-dependency-checksums',
    });
  }, 60000);

  afterEach(async () => {
    await cleanupApplicationAndAppRegistration({
      applicationUniversalIdentifier: TEST_APP_ID,
    });
  });

  it('rejects a package.json checksum that does not describe the uploaded file', async () => {
    const { errors } = await syncApplication({
      manifest: buildManifestDeclaring({
        packageJsonChecksum: computePackageJsonChecksum(
          JSON.stringify({ name: 'another-application', version: '1.0.0' }),
        ),
        yarnLockChecksum: null,
      }),
      expectToFail: true,
    });

    expect(errors?.[0]?.message).toContain(
      'Stored dependency files do not match',
    );
  });

  it('rejects a yarn.lock checksum that does not describe the uploaded file', async () => {
    jest.useRealTimers();

    await uploadApplicationFile({
      applicationUniversalIdentifier: TEST_APP_ID,
      fileFolder: 'Dependencies',
      filePath: 'yarn.lock',
      fileBuffer: Buffer.from(TEST_YARN_LOCK),
      filename: 'yarn.lock',
      contentType: 'text/plain',
      expectToFail: false,
    });

    jest.useFakeTimers();

    const { errors } = await syncApplication({
      manifest: buildManifestDeclaring({
        packageJsonChecksum: buildBaseManifest({
          appId: TEST_APP_ID,
          roleId: TEST_ROLE_ID,
        }).application.packageJsonChecksum,
        yarnLockChecksum: computeDependencyFileChecksum(
          `${TEST_YARN_LOCK}# another lockfile\n`,
        ),
      }),
      expectToFail: true,
    });

    expect(errors?.[0]?.message).toContain(
      'Stored dependency files do not match',
    );
  });
});
