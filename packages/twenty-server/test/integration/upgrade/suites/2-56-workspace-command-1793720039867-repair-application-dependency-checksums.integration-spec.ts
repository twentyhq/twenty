import {
  TEST_APPLICATION_PACKAGE_JSON,
  TEST_APPLICATION_PACKAGE_JSON_CHECKSUM,
} from 'test/integration/metadata/suites/application/constants/test-application-package-json.constant';
import { cleanupApplicationAndAppRegistration } from 'test/integration/metadata/suites/application/utils/cleanup-application-and-app-registration.util';
import { setupApplicationForSync } from 'test/integration/metadata/suites/application/utils/setup-application-for-sync.util';
import { uploadApplicationFile } from 'test/integration/metadata/suites/application/utils/upload-application-file.util';
import { getAppProviderByClassName } from 'test/integration/utils/get-app-provider-by-class-name.util';
import { computeDependencyFileChecksum } from 'twenty-shared/application';
import { v4 as uuidv4 } from 'uuid';

import { type RepairApplicationDependencyChecksumsCommand } from 'src/database/commands/upgrade-version-command/2-56/2-56-workspace-command-1793720039867-repair-application-dependency-checksums.command';
import { computeLegacyApplicationPackageChecksums } from 'src/engine/core-modules/application/application-package/utils/compute-legacy-application-package-checksums.util';
import { type DependencyChecksums } from 'src/engine/core-modules/application/application-package/utils/is-matching-dependency-checksums.util';
import { type WorkspaceCacheService } from 'src/engine/workspace-cache/services/workspace-cache.service';
import { SEED_APPLE_WORKSPACE_ID } from 'src/engine/workspace-manager/dev-seeder/core/constants/seeder-workspaces.constant';

const TEST_APP_ID = uuidv4();

const TEST_YARN_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1
`;

const STALE_CHECKSUMS: DependencyChecksums = {
  packageJsonChecksum: TEST_APPLICATION_PACKAGE_JSON_CHECKSUM,
  yarnLockChecksum: computeDependencyFileChecksum(
    `${TEST_YARN_LOCK}# another lockfile\n`,
  ),
};

const RUN_ON_WORKSPACE_ARGS = {
  workspaceId: SEED_APPLE_WORKSPACE_ID,
  options: {},
  index: 0,
  total: 1,
};

describe('2-56 workspace command - repair application dependency checksums (integration)', () => {
  let command: RepairApplicationDependencyChecksumsCommand;
  let workspaceCacheService: WorkspaceCacheService;

  const findTestApplicationChecksums =
    async (): Promise<DependencyChecksums> => {
      const [application] = await globalThis.testDataSource.query(
        `SELECT "packageJsonChecksum", "yarnLockChecksum" FROM core."application"
         WHERE "universalIdentifier" = $1 AND "workspaceId" = $2`,
        [TEST_APP_ID, SEED_APPLE_WORKSPACE_ID],
      );

      return application;
    };

  const setTestApplicationChecksums = async ({
    packageJsonChecksum,
    yarnLockChecksum,
  }: DependencyChecksums) => {
    await globalThis.testDataSource.query(
      `UPDATE core."application" SET "packageJsonChecksum" = $1, "yarnLockChecksum" = $2
       WHERE "universalIdentifier" = $3 AND "workspaceId" = $4`,
      [
        packageJsonChecksum,
        yarnLockChecksum,
        TEST_APP_ID,
        SEED_APPLE_WORKSPACE_ID,
      ],
    );

    await workspaceCacheService.invalidateAndRecompute(
      SEED_APPLE_WORKSPACE_ID,
      ['flatApplicationMaps'],
    );
  };

  beforeAll(async () => {
    command =
      getAppProviderByClassName<RepairApplicationDependencyChecksumsCommand>(
        'RepairApplicationDependencyChecksumsCommand',
      );
    workspaceCacheService = getAppProviderByClassName<WorkspaceCacheService>(
      'WorkspaceCacheService',
    );

    await setupApplicationForSync({
      applicationUniversalIdentifier: TEST_APP_ID,
      name: 'Test Application',
      description: 'App for testing the dependency checksums repair',
      sourcePath: 'test-repair-dependency-checksums',
    });

    jest.useRealTimers();

    await uploadApplicationFile({
      applicationUniversalIdentifier: TEST_APP_ID,
      fileFolder: 'Dependencies',
      filePath: 'yarn.lock',
      fileBuffer: Buffer.from(TEST_YARN_LOCK),
      filename: 'yarn.lock',
      contentType: 'text/plain',
      expectToFail: false,
    });

    jest.useFakeTimers();
  }, 60000);

  afterAll(async () => {
    await cleanupApplicationAndAppRegistration({
      applicationUniversalIdentifier: TEST_APP_ID,
    });
  });

  it('leaves stale checksums unchanged on a dry run', async () => {
    await setTestApplicationChecksums(STALE_CHECKSUMS);

    await command.runOnWorkspace({
      ...RUN_ON_WORKSPACE_ARGS,
      options: { dryRun: true },
    });

    expect(await findTestApplicationChecksums()).toEqual(STALE_CHECKSUMS);
  });

  it('replaces stale checksums with the checksums of the stored files', async () => {
    await setTestApplicationChecksums(STALE_CHECKSUMS);

    await command.runOnWorkspace(RUN_ON_WORKSPACE_ARGS);

    expect(await findTestApplicationChecksums()).toEqual({
      packageJsonChecksum: TEST_APPLICATION_PACKAGE_JSON_CHECKSUM,
      yarnLockChecksum: computeDependencyFileChecksum(TEST_YARN_LOCK),
    });
  });

  it('leaves legacy md5 checksums of the stored files unchanged', async () => {
    const legacyChecksums = computeLegacyApplicationPackageChecksums({
      packageJsonContent: TEST_APPLICATION_PACKAGE_JSON,
      yarnLockContent: TEST_YARN_LOCK,
    });

    await setTestApplicationChecksums(legacyChecksums);

    await command.runOnWorkspace(RUN_ON_WORKSPACE_ARGS);

    expect(await findTestApplicationChecksums()).toEqual(legacyChecksums);
  });
});
