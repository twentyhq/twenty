import { WORKSPACE_CUSTOM_APPLICATION_DEPENDENCIES_DIRECTORY_NAME } from 'src/engine/core-modules/application/application-package/constants/workspace-custom-application-dependencies-directory-name';
import { assertPackageJsonMatchesYarnLock } from 'src/engine/core-modules/application/application-package/utils/assert-package-json-matches-yarn-lock.util';
import { getDefaultApplicationPackageFields } from 'src/engine/core-modules/application/application-package/utils/get-default-application-package-fields.util';
import { ApplicationException } from 'src/engine/core-modules/application/application.exception';

const APPLICATION_UNIVERSAL_IDENTIFIER = '20202020-0000-4000-8000-00000000000a';

const YARN_LOCK = `__metadata:
  version: 8
  cacheKey: 10c0

"axios@npm:^1.16.1":
  version: 1.16.1
  resolution: "axios@npm:1.16.1"
  languageName: node
  linkType: hard

"test-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "test-app@workspace:."
  dependencies:
    axios: "npm:^1.16.1"
    react: "npm:19.2.0"
  languageName: unknown
  linkType: soft
`;

const YARN_1_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


axios@^1.16.1:
  version "1.16.1"
  resolved "https://registry.yarnpkg.com/axios/-/axios-1.16.1.tgz"
`;

const MATCHING_PACKAGE_JSON = {
  name: 'test-app',
  dependencies: { axios: '^1.16.1' },
  devDependencies: { react: '19.2.0' },
};

const assertMatches = (
  packageJson: Record<string, unknown>,
  yarnLockContent = YARN_LOCK,
) =>
  assertPackageJsonMatchesYarnLock({
    applicationUniversalIdentifier: APPLICATION_UNIVERSAL_IDENTIFIER,
    packageJsonContent: JSON.stringify(packageJson),
    yarnLockContent,
  });

describe('assertPackageJsonMatchesYarnLock', () => {
  it.each([
    undefined,
    WORKSPACE_CUSTOM_APPLICATION_DEPENDENCIES_DIRECTORY_NAME,
  ])('accepts the default package files (%s)', async (directory) => {
    const { packageJsonContent, yarnLockContent } =
      await getDefaultApplicationPackageFields({ directory });

    expect(() =>
      assertPackageJsonMatchesYarnLock({
        applicationUniversalIdentifier: APPLICATION_UNIVERSAL_IDENTIFIER,
        packageJsonContent,
        yarnLockContent,
      }),
    ).not.toThrow();
  });

  it('accepts a package.json whose dependencies the yarn.lock records', () => {
    expect(() => assertMatches(MATCHING_PACKAGE_JSON)).not.toThrow();
  });

  it('refuses a dependency the yarn.lock does not record', () => {
    expect(() =>
      assertMatches({
        ...MATCHING_PACKAGE_JSON,
        dependencies: { axios: '^1.16.1', 'left-pad': '^1.3.0' },
      }),
    ).toThrow(ApplicationException);
  });

  it('refuses a dependency swapped for another package', () => {
    expect(() =>
      assertMatches({
        ...MATCHING_PACKAGE_JSON,
        dependencies: { axios: 'npm:another-package@1.0.0' },
      }),
    ).toThrow(ApplicationException);
  });

  it('refuses a package.json that drops a dependency the yarn.lock records', () => {
    expect(() =>
      assertMatches({
        ...MATCHING_PACKAGE_JSON,
        devDependencies: {},
      }),
    ).toThrow(ApplicationException);
  });

  it('refuses resolutions, which override what the yarn.lock resolved', () => {
    expect(() =>
      assertMatches({
        ...MATCHING_PACKAGE_JSON,
        resolutions: { axios: 'npm:another-package@1.0.0' },
      }),
    ).toThrow(ApplicationException);
  });

  it('accepts a Yarn 1 lockfile that records every dependency', () => {
    expect(() =>
      assertMatches({ dependencies: { axios: '^1.16.1' } }, YARN_1_LOCK),
    ).not.toThrow();
  });

  it('refuses a Yarn 1 lockfile that misses a dependency', () => {
    expect(() =>
      assertMatches(
        { dependencies: { axios: '^1.16.1', 'left-pad': '^1.3.0' } },
        YARN_1_LOCK,
      ),
    ).toThrow(ApplicationException);
  });
});
